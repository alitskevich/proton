import { posix } from "node:path";
import { writeFileContent } from "./utils/files";
import { generateFromJsonFiles, overlayLang, readJsonFiles } from "./utils/jsonFiles";
import { jsonSource } from "./utils/jsonSource";

/** One `<name>.json` vocabulary: its member rows, each `{ id, … }`; a `$comment` is written above it. */
type ShapeSource = { $comment?: string; items: Record<string, unknown>[] };

const shapeRows = (name: string, shape: ShapeSource) => {
  if (!Array.isArray(shape?.items)) throw new Error(`${name}.json: expected { "items": [...] }`);
  return shape.items;
};

const shapeSource = (name: string, shape: ShapeSource) =>
  [
    ...(shape.$comment ? shape.$comment.split("\n").map((l) => `// ${l}`) : []),
    `export const ${name}Shape = ${jsonSource(shapeRows(name, shape) as never)} as const;`,
  ].join("\n");

/**
 * Generates a shapes module: one `export const <name>Shape = [...] as const` per `<name>.json` in
 * `sourceDir`. The `as const` is the point — a `.json` import types its values as plain `string`,
 * while the generated literal keeps every id a literal type, so a `z.enum` built from it stays exact.
 * `$`-keys are notes, not data — see `jsonSource`.
 *
 * @param sourceDir The folder of `.json` vocabularies (`{ items }`), scanned flat.
 * @param outFile Destination module.
 */
export function generateShapes({ sourceDir, outFile, lang }: { sourceDir: string; outFile: string; lang?: string }) {
  const shapes = readJsonFiles(sourceDir, lang);

  writeFileContent(
    posix.resolve(outFile),
    `// GENERATED by \`proton/ops/generate-shapes.ts\` from \`${sourceDir}/*.json\`${lang ? ` (\`:${lang}\`)` : ""} — do not edit.
${shapes.map(([name, shape]) => shapeSource(name, shape as ShapeSource)).join("\n\n")}
`
  );

  console.log(`Generate shapes: ${sourceDir} -> ${outFile} (${shapes.length})`);
}

// `bun ../proton/ops/generate-shapes.ts <sourceDir> <outFile> [--watch]`:
//   bun ../proton/ops/generate-shapes.ts .model/enums packages/bbb-enums/shapes.ts
// `--watch` regenerates on every `.json` change; a broken file is reported and the watch goes on.
// `--overlay=<lang>` writes that language's overlay instead of the base — see `readJsonFiles`.
const [sourceDir, outFile] = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!sourceDir || !outFile) throw new Error("usage: generate-shapes.ts <sourceDir> <outFile> [--overlay=<lang>] [--watch]");

generateFromJsonFiles(sourceDir, () => generateShapes({ sourceDir, outFile, lang: overlayLang() }));

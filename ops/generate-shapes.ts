import { posix } from "node:path";
import { writeFileContent } from "./utils/files";
import { generateFromJsonFiles, readJsonFiles } from "./utils/jsonFiles";

/** One `<name>.json` vocabulary: its member rows, each `{ id, … }`. */
type ShapeSource = { items: Record<string, unknown>[] };

const shapeRows = (name: string, shape: ShapeSource) => {
  if (!Array.isArray(shape?.items)) throw new Error(`${name}.json: expected { "items": [...] }`);
  return shape.items;
};

/**
 * Generates a shapes module: one `export const <name>Shape = [...] as const` per `<name>.json` in
 * `sourceDir`. The `as const` is the point — a `.json` import types its values as plain `string`,
 * while the generated literal keeps every id a literal type, so a `z.enum` built from it stays exact.
 *
 * @param sourceDir The folder of `.json` vocabularies (`{ items }`), scanned flat.
 * @param outFile Destination module.
 */
export function generateShapes({ sourceDir, outFile }: { sourceDir: string; outFile: string }) {
  const shapes = readJsonFiles(sourceDir);

  writeFileContent(
    posix.resolve(outFile),
    `// GENERATED by \`proton/ops/generate-shapes.ts\` from \`${sourceDir}/*.json\` — do not edit.
${shapes.map(([name, shape]) => `export const ${name}Shape = ${JSON.stringify(shapeRows(name, shape as ShapeSource), null, 2)} as const;`).join("\n\n")}
`
  );

  console.log(`Generate shapes: ${sourceDir} -> ${outFile} (${shapes.length})`);
}

// `bun ../proton/ops/generate-shapes.ts <sourceDir> <outFile> [--watch]`:
//   bun ../proton/ops/generate-shapes.ts .model/enums packages/bbb-enums/shapes.ts
// `--watch` regenerates on every `.json` change; a broken file is reported and the watch goes on.
const [sourceDir, outFile] = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!sourceDir || !outFile) throw new Error("usage: generate-shapes.ts <sourceDir> <outFile> [--watch]");

generateFromJsonFiles(sourceDir, () => generateShapes({ sourceDir, outFile }));

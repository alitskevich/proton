import { posix } from "node:path";
import { generateFromJsonFiles, readJsonFiles, writeFileContent } from "../utils-files/index.ts";

/** One `<name>.json` vocabulary: its member rows, each `{ id, … }`; a `$comment` becomes the doc comment. */
type EnumSource = { $comment?: string; items: { id?: unknown }[] };

const pascal = (name: string) => name.charAt(0).toUpperCase() + name.slice(1);

const enumSource = (name: string, source: EnumSource) => {
  if (!Array.isArray(source?.items)) throw new Error(`${name}.json: expected { "items": [...] }`);
  const ids = source.items.map(({ id }) => {
    if (typeof id !== "string") throw new Error(`${name}.json: every item needs a string "id"`);
    return JSON.stringify(id);
  });
  const Name = pascal(name);
  return [
    ...(source.$comment ? ["/**", ...source.$comment.split("\n").map((l) => ` * ${l}`), " */"] : []),
    `export const Z${Name} = z.enum([${ids.join(", ")}]);`,
    "",
    `export type T${Name} = z.infer<typeof Z${Name}>;`,
  ].join("\n");
};

/**
 * Generates a Zod module: per `<name>.json` in `sourceDir`, `export const Z<Name> = z.enum([...ids])` and its
 * `export type T<Name>`, the ids as literals so the type stays exact. The vocabulary's `$comment` is the doc
 * comment. The importing project provides `zod`.
 *
 * @param sourceDir The folder of `.json` vocabularies (`{ items }`), scanned flat.
 * @param outFile Destination module.
 */
export function generateEnums({ sourceDir, outFile }: { sourceDir: string; outFile: string }) {
  const sources = readJsonFiles(sourceDir);

  writeFileContent(
    posix.resolve(outFile),
    `// GENERATED by \`proton/ops/generate-enums.ts\` from \`${sourceDir}/*.json\` — do not edit.
import { z } from "zod";

${sources.map(([name, source]) => enumSource(name, source as EnumSource)).join("\n\n")}
`
  );

  console.log(`Generate enums: ${sourceDir} -> ${outFile} (${sources.length})`);
}

// `proton generate-enums <sourceDir> <outFile> [--watch]`:
//   proton generate-enums ../../.meta/enums src/schema.ts
// `--watch` regenerates on every `.json` change; a broken file is reported and the watch goes on.
const [sourceDir, outFile] = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!sourceDir || !outFile) throw new Error("usage: generate-enums.ts <sourceDir> <outFile> [--watch]");

generateFromJsonFiles(sourceDir, () => generateEnums({ sourceDir, outFile }));

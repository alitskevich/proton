import { posix } from "node:path";
import { writeFileContent } from "./utils/files";
import { generateFromJsonFiles, overlayLang, readJsonFiles } from "./utils/jsonFiles";
import { jsonSource } from "./utils/jsonSource";

/**
 * Generates a strings module: one `export const <name> = { … }` per `<name>.json` in `sourceDir`,
 * each a UI-strings area (an object of texts, nested groups allowed). A `.json` holds literal text
 * only, so a value computed elsewhere is written into it as text. `$`-keys are notes, not data — see
 * `jsonSource`.
 *
 * @param sourceDir The folder of `.json` string areas, scanned flat.
 * @param outFile Destination module.
 */
export function generateStrings({ sourceDir, outFile, lang }: { sourceDir: string; outFile: string; lang?: string }) {
  const areas = readJsonFiles(sourceDir, lang);
  for (const [name, area] of areas) {
    if (!area || typeof area !== "object" || Array.isArray(area)) throw new Error(`${name}.json: expected an object`);
  }

  writeFileContent(
    posix.resolve(outFile),
    `// GENERATED by \`proton/ops/generate-strings.ts\` from \`${sourceDir}/*.json\`${lang ? ` (\`:${lang}\`)` : ""} — do not edit.
${areas.map(([name, area]) => `export const ${name} = ${jsonSource(area as never)};`).join("\n\n")}
`
  );

  console.log(`Generate strings: ${sourceDir} -> ${outFile} (${areas.length})`);
}

// `bun ../proton/ops/generate-strings.ts <sourceDir> <outFile> [--watch]`:
//   bun ../proton/ops/generate-strings.ts .meta/strings packages/bbb-rc/strings.ts
// `--watch` regenerates on every `.json` change; a broken file is reported and the watch goes on.
// `--overlay=<lang>` writes that language's overlay instead of the base — see `readJsonFiles`.
const [sourceDir, outFile] = process.argv.slice(2).filter((a) => !a.startsWith("--"));
if (!sourceDir || !outFile) throw new Error("usage: generate-strings.ts <sourceDir> <outFile> [--overlay=<lang>] [--watch]");

generateFromJsonFiles(sourceDir, () => generateStrings({ sourceDir, outFile, lang: overlayLang() }));

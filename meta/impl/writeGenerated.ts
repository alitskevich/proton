import { posix } from "node:path";
import { writeFileContent } from "arrmatura-host/files";

/**
 * Writes a module `proton generate-meta` generates: the GENERATED header naming its sources (and the overlay's
 * `lang`), then `body`; logs one line with `count`, what it generated.
 */
export function writeGenerated({
  kind,
  sources,
  outFile,
  lang,
  body,
  count,
}: {
  /** The module's kind, for the log: `enums`. */
  kind: string;
  /** The files it is generated from, as the header names them: `.meta/enums/*.json`. */
  sources: string[];
  outFile: string;
  lang?: string;
  body: string;
  count: string | number;
}) {
  const quoted = sources.map((source) => `\`${source}\``);
  const last = quoted.pop();
  const from = quoted.length ? `${quoted.join(", ")} and ${last}` : last;
  const overlay = lang ? ` (\`:${lang}\`)` : "";
  writeFileContent(
    posix.resolve(outFile),
    `// GENERATED by \`proton generate-meta\` from ${from}${overlay} — do not edit.\n${body}\n`,
  );
  console.log(`Generate ${kind}: ${sources.join(" + ")} -> ${outFile} (${count})`);
}
